    // -----------------------------------------------------------------------
    // Regression: generic return types must not corrupt PlantUML arrows
    // (previously a global <,> → ~ replacement at PNG-export time turned
    //  ..> into ..~ and produced "Syntax Error?" images)
    // -----------------------------------------------------------------------

    @Test
    void buildPlantUmlClassSource_genericReturnTypes_passPlantUmlSyntaxCheck() {
        EndpointInfo endpoint = EndpointInfo.builder()
                .httpVerb(HttpVerb.POST)
                .pathTemplate("/api/accommodationRequests/fillNniContract")
                .controllerClass("AccommodationRequestController")
                .methodName("fillNniContract")
                .framework("Spring")
                .build();

        CallNode serviceNode = new CallNode(
                "AccommodationRequestService", "updateNniContract",
                CallNode.Role.SERVICE,
                false, "Collection<AccommodationRequest>",
                List.of("IAccommodationRequestService"), "BaseService",
                List.of(),
                List.of()
        );

        CallNode root = new CallNode(
                "AccommodationRequestController", "fillNniContract",
                CallNode.Role.CONTROLLER,
                false, "Collection<AccommodationRequestDTO>",
                List.of(), null,
                List.of(),
                List.of(serviceNode)
        );

        HttpCallInfo httpCall = new HttpCallInfo("fillNniContract", HttpVerb.POST,
                "/api/accommodationRequests/fillNniContract", "AccommodationRequestDTO", "FillNniContractDTO");
        ServiceInfo angularService = new ServiceInfo("AccommodationRequestService",
                "accommodation-request.service.ts", List.of(httpCall));
        MatchedFlow flow = new MatchedFlow(angularService, httpCall, endpoint, null, null);

        String puml = renderer.buildPlantUmlClassSource(
                "POST /api/accommodationRequests/fillNniContract", flow, root);

        // Arrows must survive intact
        assertTrue(puml.contains("..|>"), "Implements arrow ..|> must be intact");
        assertTrue(puml.contains("--|>"), "Extends arrow --|> must be intact");
        assertFalse(puml.contains("..~"), "Arrow must not be corrupted into ..~");
        assertFalse(puml.contains("--~"), "Arrow must not be corrupted into --~");
        // Generics escaped only inside member text
        assertTrue(puml.contains("Collection~AccommodationRequestDTO~"),
                "Generic type must be tilde-escaped in member text");

        // The PlantUML engine itself must accept the source without a syntax error
        net.sourceforge.plantuml.syntax.SyntaxResult syntax =
                net.sourceforge.plantuml.syntax.SyntaxChecker.checkSyntax(puml);
        assertFalse(syntax.isError(),
                "PlantUML reports a syntax error in:\n" + puml + "\nErrors: " + syntax.getErrors());

        // Sanity check: the checker DOES flag the old corrupted arrow form, so the
        // assertion above is meaningful.
        String corrupted = puml.replace("..|>", "..|~").replace("--|>", "--|~");
        assertTrue(net.sourceforge.plantuml.syntax.SyntaxChecker.checkSyntax(corrupted).isError(),
                "SyntaxChecker should reject the old corrupted arrow form");
    }
