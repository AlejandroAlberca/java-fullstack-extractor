    @Test
    void classesOutputPath_derivesCorrectName() {
        Path main   = Path.of("/output/api-spec.md");
        Path result = ClassDiagramRenderer.classesOutputPath(main);
        assertEquals("api-spec-classes.md", result.getFileName().toString());
    }

    // -----------------------------------------------------------------------
